"""Generate ordinary C; goto-cc parses CLI expressions and checks their types."""
import json


def generate(architecture, bits, entry, stack_size, preconditions, postconditions):
    aliases = []
    if architecture == "x86":
        names = "rax rcx rdx rbx rsp rbp rsi rdi r8 r9 r10 r11 r12 r13 r14 r15".split()
        registers = [(name, "uint64_t", f"asmc_get_reg(&s, ASMC_{name.upper()}, 8)")
                     for name in names]
        registers += [(name, "uint8_t", f"asmc_get_reg(&s, ASMC_{name.upper()}, 1)")
                      for name in "cf pf af zf sf of df".split()]
        views = [
            ("rax", "eax", "ax", "al"), ("rcx", "ecx", "cx", "cl"),
            ("rdx", "edx", "dx", "dl"), ("rbx", "ebx", "bx", "bl"),
            ("rsp", "esp", "sp", "spl"), ("rbp", "ebp", "bp", "bpl"),
            ("rsi", "esi", "si", "sil"), ("rdi", "edi", "di", "dil"),
            *[(f"r{i}", f"r{i}d", f"r{i}w", f"r{i}b") for i in range(8, 16)],
        ]
        for parent, dword, word, byte in views:
            aliases += [(name, f"uint{width}_t", parent, 0)
                        for name, width in ((dword, 32), (word, 16), (byte, 8))]
        aliases += [(name, "uint8_t", parent, 8)
                    for name, parent in (("ah", "rax"), ("ch", "rcx"), ("dh", "rdx"), ("bh", "rbx"))]
        abi = "sysv"
    else:
        names = ("zero ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 "
                 "s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6").split()
        registers = [(name, f"uint{bits}_t", f"asmc_riscv_reg(&s, {index})")
                     for index, name in enumerate(names)]
        abi = "riscv"

    def snapshot(which):
        assignments = [f"  {which}.{name} = ({kind}){read};" for name, kind, read in registers]
        # Derive every alias from the captured full register: no extra machine
        # reads or independently nondeterministic values for overlapping views.
        for name, kind, parent, shift in aliases:
            value = f"{which}.{parent}"
            if shift:
                value += f" >> {shift}"
            assignments.append(f"  {which}.{name} = ({kind})({value});")
        return assignments

    lines = [
        "/* Generated by ASMC. Local uninitialized registers/bytes are nondeterministic",
        " * in CBMC. in/out contain registers only, not snapshots of memory.",
        " * Adapt this file and use --harness for allocations or richer contracts. */",
        f'#include "asmc_{architecture}.h"',
        "",
        "struct asmc_demo_registers {",
        *[f"  {kind} {name};" for name, kind, _ in registers],
        *[f"  {kind} {name};" for name, kind, _, _ in aliases],
        "};",
        "",
        f"void {entry}(void) {{",
        f"  uint8_t stack[{stack_size}];",
        "  struct asmc_state s;",
        "#ifdef ASMC_OBJECT_MEMORY",
        f"  struct asmc_{abi}_frame frame = asmc_{abi}_enter_objects(&s, stack, sizeof(stack));",
        "#else",
    ]
    if architecture == "x86":
        lines += ["  struct asmc_sysv_frame frame = asmc_sysv_enter_at_end(",
                  "      &s, stack, UINT64_C(0x1000), sizeof(stack));"]
    else:
        lines += ["  struct asmc_riscv_frame frame = asmc_riscv_enter(",
                  "      &s, stack, UINT64_C(0x1000), sizeof(stack),",
                  "      (UINT64_C(0x1000) + sizeof(stack)) & ~UINT64_C(15));"]
    lines += ["#endif", "  struct asmc_demo_registers in;"]
    # Individual assignments also make input/output values visible in CBMC traces.
    lines += snapshot("in")
    lines += [f"  __CPROVER_assume(({expression}));" for expression in preconditions]
    lines += ["  ASMC_TARGET(&s);", f"  asmc_{abi}_check(&s, &frame);",
              "  struct asmc_demo_registers out;"]
    lines += snapshot("out")
    lines += [f"  __CPROVER_assert(({expression}), {json.dumps('post: ' + expression)});"
              for expression in postconditions]
    lines += ["}", ""]
    return "\n".join(lines)
